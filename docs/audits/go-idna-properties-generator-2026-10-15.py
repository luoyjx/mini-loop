#!/usr/bin/env python3
"""Rebuild the fixed Source IDNA properties; no network or Go execution."""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import subprocess
import sys
import unicodedata
from pathlib import Path

import idna
from idna import core, idnadata, intranges


ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "var/go-idna-implementation-2026-10-14"
GO_PATH = ROOT / "go/provider/idna_tables.go"
LICENSE_PATH = ROOT / "go/provider/IDNA_DATA_LICENSE.txt"
EXPECTED = {
    "python_implementation": "CPython",
    "python_version": "3.11.3",
    "unicode_version": "14.0.0",
    "idna_version": "3.18",
    "idna_table_unicode_version": "17.0.0",
}


def reference(path: Path) -> dict:
    data = path.read_bytes()
    try:
        name = str(path.relative_to(ROOT))
    except ValueError:
        name = str(path)
    return {"path": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


def decode_ranges(encoded: tuple[int, ...]) -> list[tuple[int, int]]:
    result = [(item >> 32, (item & 0xFFFFFFFF) - 1) for item in encoded]
    validate_ranges(result)
    return result


def validate_ranges(ranges: list[tuple[int, int]]) -> None:
    previous = -1
    for first, last in ranges:
        if not (previous < first <= last <= 0x10FFFF):
            raise RuntimeError(f"unordered or invalid Source range: {first:x}..{last:x}")
        previous = last


class Ranges:
    def __init__(self) -> None:
        self.values: list[tuple[int, int]] = []
        self.first: int | None = None

    def accept(self, codepoint: int, included: bool) -> None:
        if included and self.first is None:
            self.first = codepoint
        elif not included and self.first is not None:
            self.values.append((self.first, codepoint - 1))
            self.first = None

    def finish(self) -> list[tuple[int, int]]:
        self.accept(0x110000, False)
        validate_ranges(self.values)
        return self.values


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated bytes without writing")
    args = parser.parse_args()
    actual = {
        "python_implementation": platform.python_implementation(),
        "python_version": platform.python_version(),
        "unicode_version": unicodedata.unidata_version,
        "idna_version": idna.__version__,
        "idna_table_unicode_version": idnadata.__version__,
    }
    if actual != EXPECTED:
        raise RuntimeError(f"fixed Source profile required: {actual!r}")
    fixture_path = ROOT / "go/testdata/python-provider-idna.json"
    fixture = json.loads(fixture_path.read_text())
    for name, module in [("idna/core.py", core), ("idna/idnadata.py", idnadata), ("idna/intranges.py", intranges)]:
        if reference(Path(module.__file__))["sha256"] != fixture["source_sha256"][name]:
            raise RuntimeError(f"Source file drift: {name}")

    tables = {
        "PValid": decode_ranges(idnadata.codepoint_classes["PVALID"]),
        "ContextJ": decode_ranges(idnadata.codepoint_classes["CONTEXTJ"]),
        "ContextO": decode_ranges(idnadata.codepoint_classes["CONTEXTO"]),
    }
    for name in ["Greek", "Hebrew", "Han", "Hiragana", "Katakana"]:
        tables[name] = decode_ranges(idnadata.scripts[name])

    direction, virama, mark = Ranges(), Ranges(), Ranges()
    for codepoint in range(0x110000):
        value = chr(codepoint)
        direction.accept(codepoint, unicodedata.bidirectional(value) != "")
        virama.accept(codepoint, unicodedata.combining(value) == 9)
        mark.accept(codepoint, unicodedata.category(value).startswith("M"))
    tables["KnownDirection"] = direction.finish()
    tables["Virama"] = virama.finish()
    tables["Mark"] = mark.finish()

    joining = []
    for kind in ["L", "R", "D", "T"]:
        joining.extend((first, last, kind) for first, last in decode_ranges(idnadata.joining_types[kind]))
    joining.sort()
    validate_ranges([(first, last) for first, last, _ in joining])

    data_hash = reference(Path(idnadata.__file__))["sha256"]
    lines = [
        "// Code generated by var/go-idna-implementation-2026-10-14/generate-idna-tables.py; DO NOT EDIT.",
        "// Source: idna 3.18 data (Unicode 17.0.0), CPython 3.11.3 unicodedata (Unicode 14.0.0).",
        f"// idna/idnadata.py SHA-256: {data_hash}",
        "// Properties are complete Source ranges, not a hostname fixture allowlist.",
        "// Rebuild from the repository root:",
        "//   .venv/bin/python var/go-idna-implementation-2026-10-14/generate-idna-tables.py",
        "// See IDNA_DATA_LICENSE.txt for retained upstream notices.",
        "", "package provider", "", "import \"sort\"", "",
        "// sourceIDNAInterval uses inclusive rune endpoints.",
        "type sourceIDNAInterval struct {", "\tfirst, last rune", "}", "",
        "type sourceIDNAJoiningInterval struct {", "\tfirst, last rune", "\tkind byte", "}", "",
        "func sourceIDNAContains(value rune, intervals []sourceIDNAInterval) bool {",
        "\tindex := sort.Search(len(intervals), func(index int) bool { return intervals[index].last >= value })",
        "\treturn index < len(intervals) && intervals[index].first <= value", "}", "",
    ]
    for name, ranges in tables.items():
        lines.extend([
            f"func sourceIDNA{name}(value rune) bool {{",
            f"\treturn sourceIDNAContains(value, sourceIDNA{name}Intervals[:])", "}", "",
            f"var sourceIDNA{name}Intervals = [...]sourceIDNAInterval{{",
        ])
        lines.extend(f"\t{{0x{first:X}, 0x{last:X}}}," for first, last in ranges)
        lines.extend(["}", ""])
    lines.extend([
        "// sourceIDNAJoiningType retains the L/R/D/T classes consumed by Source CONTEXTJ.",
        "// Other classes are equivalent to no matching contextual class and return zero.",
        "func sourceIDNAJoiningType(value rune) byte {",
        "\tindex := sort.Search(len(sourceIDNAJoiningIntervals), func(index int) bool { return sourceIDNAJoiningIntervals[index].last >= value })",
        "\tif index < len(sourceIDNAJoiningIntervals) && sourceIDNAJoiningIntervals[index].first <= value {",
        "\t\treturn sourceIDNAJoiningIntervals[index].kind", "\t}", "\treturn 0", "}", "",
        "var sourceIDNAJoiningIntervals = [...]sourceIDNAJoiningInterval{",
    ])
    lines.extend(f"\t{{0x{first:X}, 0x{last:X}, '{kind}'}}," for first, last, kind in joining)
    lines.extend(["}", ""])
    go_data = subprocess.run(
        ["gofmt"], input="\n".join(lines).encode(), capture_output=True, check=True
    ).stdout

    idna_license = Path(idna.__file__).parent.parent / "idna-3.18.dist-info/licenses/LICENSE.md"
    python_license = Path(sys.executable).resolve().parents[1] / "lib/python3.11/LICENSE.txt"
    license_data = (
        "Fixed Source IDNA compatibility data\n"
        "===================================\n\n"
        "idna_tables.go derives IDNA validity/context/script/joining ranges from\n"
        "idna 3.18 idnadata.py (Unicode 17.0.0), and direction-known, virama and\n"
        "mark ranges from CPython 3.11.3 unicodedata (Unicode 14.0.0).\n"
        "The exact upstream notices below are retained without modification.\n\n"
        "idna 3.18: LICENSE.md\n"
        "---------------------\n\n"
    ).encode() + idna_license.read_bytes() + (
        "\nCPython 3.11.3: LICENSE.txt\n"
        "--------------------------\n\n"
    ).encode() + python_license.read_bytes()

    for path, data in [(GO_PATH, go_data), (LICENSE_PATH, license_data)]:
        if args.check:
            if path.read_bytes() != data:
                raise RuntimeError(f"generated byte mismatch: {path}")
        else:
            path.write_bytes(data)
    if args.check:
        print(json.dumps({"status": "generated_bytes_match", "outputs": [reference(GO_PATH), reference(LICENSE_PATH)]}))
        return

    record = {
        "status": "generated_fixed_source_properties_only_not_runtime_validation",
        "profile": actual,
        "inputs": [reference(Path(module.__file__)) for module in [core, idnadata, intranges, unicodedata]],
        "interpreter": reference(Path(sys.executable).resolve()),
        "fixture": reference(fixture_path),
        "generator": reference(Path(__file__).resolve()),
        "license_inputs": [reference(idna_license), reference(python_license)],
        "outputs": [reference(GO_PATH), reference(LICENSE_PATH)],
        "properties": {name: {"ranges": len(ranges), "codepoints": sum(last - first + 1 for first, last in ranges)} for name, ranges in tables.items()},
        "joining": {"ranges": len(joining), "classes": ["L", "R", "D", "T"], "other_classes_return_zero": True},
        "apis": [f"sourceIDNA{name}(rune) bool" for name in tables] + ["sourceIDNAJoiningType(rune) byte"],
        "rebuild_command": ".venv/bin/python var/go-idna-implementation-2026-10-14/generate-idna-tables.py",
        "scope": "Only generated Unicode property tables; no Go test/build, Source capture, dependency installation or runtime parity claim.",
    }
    (OUT / "idna-tables-provenance.json").write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"status": record["status"], "outputs": record["outputs"], "properties": record["properties"], "joining": record["joining"]}))


if __name__ == "__main__":
    main()
